//! `docs/RULES.md`: the registry as a document, and the rules that keep the documents honest.
//!
//! The document is generated (`cargo xtask rules --write`), and the rule `rules-doc` fails when
//! the committed file differs from what the registry generates, so it cannot drift. The rule
//! `planned-task` ties every planned mechanism to a task (ADR-0011), so the backlog cannot be
//! forgotten either.

use super::registry::{self, BanScope, RuleKind};
use super::{Violation, lints, style_guide};
use std::fs;
use std::io;
use std::path::Path;

/// The generated document, relative to the root.
pub const RULES_DOC: &str = "docs/RULES.md";

/// The command that regenerates the document.
const WRITE_COMMAND: &str = "cargo xtask rules --write";

/// Where the plans that are being worked on live (ADR-0011).
const ACTIVE_PLANS: &str = "docs/exec-plans/active";

/// The task list of one plan (ADR-0011).
const TASKS_FILE: &str = "tasks.json";

/// Renders `docs/RULES.md` for the tree at `root`: the tidy rules and bans from the registry,
/// the dylint lints declared in `lints/src/`, the planned mechanisms, and the number of rules
/// that the style guide leaves to review.
pub fn render(root: &Path) -> io::Result<String> {
    let style_guide = fs::read_to_string(root.join(style_guide::STYLE_GUIDE))?;
    let review_count = style_guide::review_count(&style_guide);
    let mut lines: Vec<String> = Vec::new();
    lines.extend(header_section());
    lines.extend(rules_section());
    lines.extend(bans_section());
    lines.extend(lints_section(&lints::declared(root)?, &lints::documented(root)?));
    lines.extend(planned_section());
    lines.extend(review_section(review_count));
    lines.extend(foreign_gate_section());
    assert!(lines.iter().all(|line| !line.contains('\n')), "every element is one line");
    Ok(lines.join("\n") + "\n")
}

/// The rule `rules-doc`: the committed document is what [`render`] generates.
pub fn check(root: &Path) -> io::Result<Vec<Violation>> {
    let expected = render(root)?;
    let path = Path::new(RULES_DOC);
    let Ok(actual) = fs::read_to_string(root.join(path)) else {
        let message = format!(
            "{RULES_DOC} is missing; run `{WRITE_COMMAND}` and commit the result (ADR-0018)"
        );
        return Ok(vec![Violation::new(path, 0, "rules-doc", message)]);
    };
    if actual == expected {
        return Ok(Vec::new());
    }
    let same_lines = actual.lines().zip(expected.lines()).take_while(|(a, b)| a == b).count();
    let line = u32::try_from(same_lines + 1).expect("documents have < 2^32 lines");
    let message = format!(
        "{RULES_DOC} is stale: it differs from the registry from this line on. Do not edit it by \
         hand; run `{WRITE_COMMAND}` and commit the result (ADR-0018)"
    );
    Ok(vec![Violation::new(path, line, "rules-doc", message)])
}

/// The rule `planned-task`: every planned mechanism has a task with the same id in some
/// `docs/exec-plans/active/<plan>/tasks.json`.
pub fn check_planned_tasks(root: &Path) -> io::Result<Vec<Violation>> {
    let mut tasks = String::new();
    if root.join(ACTIVE_PLANS).is_dir() {
        for plan in super::entries_of(root, ACTIVE_PLANS)? {
            let file = root.join(plan).join(TASKS_FILE);
            if file.is_file() {
                tasks.push_str(&fs::read_to_string(file)?);
            }
        }
    }
    // Without a JSON parser, compare without whitespace: `"id": "x"` and `"id":"x"` are equal.
    tasks.retain(|character| !character.is_whitespace());
    let mut violations = Vec::new();
    for planned in registry::PLANNED {
        if !tasks.contains(&format!("\"id\":\"{}\"", planned.id)) {
            let message = format!(
                "planned mechanism `{id}` has no task; add a task with `\"id\": \"{id}\"` to a \
                 `{TASKS_FILE}` under {ACTIVE_PLANS}/, or delete the row from PLANNED once it is \
                 built (ADR-0018)",
                id = planned.id
            );
            violations.push(Violation::new(Path::new(ACTIVE_PLANS), 0, "planned-task", message));
        }
    }
    Ok(violations)
}

fn header_section() -> Vec<String> {
    vec![
        "# Rules that are checked mechanically".to_owned(),
        String::new(),
        format!(
            "<!-- Generated by `{WRITE_COMMAND}` from `xtask/src/tidy/registry.rs`. Do not edit: \
             the tidy rule `rules-doc` fails when this file is stale. -->"
        ),
        String::new(),
        "What each tool checks today, and what is only promised so far. `docs/TIGER_STYLE.md` \
         tags every rule with the mechanism that enforces it, and tidy checks those tags against \
         this registry (rule `doc-tag`)."
            .to_owned(),
    ]
}

fn rules_section() -> Vec<String> {
    let mut lines = vec![
        String::new(),
        "## Tidy rules".to_owned(),
        String::new(),
        "`cargo xtask tidy`. A source rule is decided from one file, so the edit hook can run it \
         on the file that was just edited. A workspace rule needs the whole tree. Every source \
         rule has a firing and a passing example in `xtask/fixtures/tidy/`. What a rule sees and \
         misses is here, not in `docs/TIGER_STYLE.md`, which states the rule and its reason \
         (rule `doc-tool-name`)."
            .to_owned(),
        String::new(),
        row(&["Rule", "Kind", "What it requires", "What it sees and misses", "Reference"]),
        row(&["---"; 5]),
    ];
    for rule in registry::RULES {
        let kind = match rule.kind {
            RuleKind::Source => "source",
            RuleKind::Workspace => "workspace",
        };
        lines.push(row(&[&code(rule.id), kind, rule.summary, rule.detail, rule.reference]));
    }
    lines
}

fn bans_section() -> Vec<String> {
    let mut lines = vec![
        String::new(),
        "## Tidy bans".to_owned(),
        String::new(),
        "Declarative source rules: a ban is one row in `PATH_BANS` or `MACRO_BANS` plus two \
         fixtures. Bans also apply inside macro invocations."
            .to_owned(),
        String::new(),
        row(&["Rule", "Bans", "Allowed in", "Applies to", "Message"]),
        row(&["---"; 5]),
    ];
    for ban in registry::PATH_BANS {
        let bans =
            format!("paths that start with `{}::`, as calls, types and imports", ban.segment);
        let scope = match ban.scope {
            BanScope::Everywhere => "every Rust file",
            BanScope::NamiCrates => "nami crates",
        };
        lines.push(row(&[&code(ban.id), &bans, &code_list(ban.allowed), scope, ban.message]));
    }
    for ban in registry::MACRO_BANS {
        let names: Vec<String> = ban.names.iter().map(|name| format!("{name}!")).collect();
        let names: Vec<&str> = names.iter().map(String::as_str).collect();
        let bans = format!("the macros {}", code_list(&names));
        let allowed = code_list(ban.allowed);
        lines.push(row(&[&code(ban.id), &bans, &allowed, "every Rust file", ban.message]));
    }
    lines
}

fn lints_section(declared: &[lints::DylintLint], documented: &[(String, String)]) -> Vec<String> {
    let mut lines = vec![
        String::new(),
        "## Dylint lints".to_owned(),
        String::new(),
        format!(
            "`just dylint`, part of `just check-full`. Declared in `{}/`, on a pinned nightly. \
             A lint gates only at `Deny`, because the recipe does not deny warnings. What it sees \
             and misses is the `### What it does` section of its doc comment.",
            lints::LINT_SOURCES
        ),
        String::new(),
        row(&["Lint", "Level", "What it reports", "What it sees and misses"]),
        row(&["---"; 4]),
    ];
    for lint in declared {
        let documentation = documented.iter().find(|(name, _)| *name == lint.name);
        let detail = documentation.map_or("", |(_, text)| text.as_str());
        lines.push(row(&[&code(&lint.name), &lint.level, &lint.description, detail]));
    }
    lines.extend([
        String::new(),
        "## Clippy and rustc lints".to_owned(),
        String::new(),
        "The lint tables are `[workspace.lints.rust]` and `[workspace.lints.clippy]` in the root \
         `Cargo.toml`. The workspace lints are pedantic plus selected restriction lints, and \
         `-D warnings` applies in `just` and CI. The banned methods and types, each with a reason \
         that names the replacement, are in `clippy.toml`. `just clippy` denies warnings. A lint \
         that a tag in `docs/TIGER_STYLE.md` names cannot be removed or set to `allow` without \
         `doc-tag` failing."
            .to_owned(),
    ]);
    lines
}

fn planned_section() -> Vec<String> {
    let mut lines = vec![
        String::new(),
        "## Planned mechanisms".to_owned(),
        String::new(),
        format!(
            "Promised in the documents and not built yet. The style guide tags the rules they \
             will enforce `[planned:<id>]`. Each has a task with the same id under \
             `{ACTIVE_PLANS}/` (rule `planned-task`)."
        ),
        String::new(),
        row(&["Id", "Intended mechanism", "What it will check", "Reference"]),
        row(&["---"; 4]),
    ];
    for planned in registry::PLANNED {
        let id = code(planned.id);
        lines.push(row(&[&id, planned.mechanism, planned.description, planned.reference]));
    }
    lines
}

fn review_section(review_count: usize) -> Vec<String> {
    vec![
        String::new(),
        "## Rules left to review".to_owned(),
        String::new(),
        format!(
            "`{}` carries {review_count} `[review]` tags: rules, or parts of rules, that no tool \
             checks and that the AI reviewer and the human reviewer have to hold. A rule that \
             keeps getting broken in review is a candidate for a mechanism.",
            style_guide::STYLE_GUIDE
        ),
    ]
}

fn foreign_gate_section() -> Vec<String> {
    let skipped = code_list(&registry::REGISTRY_BOUND_RULES);
    let style_guide_rules = code_list(&style_guide::STYLE_GUIDE_RULES);
    vec![
        String::new(),
        "## Checking another revision's tree".to_owned(),
        String::new(),
        format!(
            "`cargo xtask tidy --root <dir>` checks another tree with this binary. With \
             `--policy <dir>` it acts as a foreign gate: CI runs the base branch's tidy on a \
             pull request's tree, so that a pull request cannot pass by weakening its own gate. \
             In that mode the `#[expect]` budget is read from the policy directory, and the rules \
             that compare the tree's documents with the binary's own registry are skipped, \
             because a tree with a different registry fails them by construction: {skipped}. \
             The style guide is not read at all, so its rules are skipped too, including those \
             that do not depend on the registry: {style_guide_rules}."
        ),
    ]
}

/// One row of a Markdown table. A `|` inside a cell is escaped.
fn row(cells: &[&str]) -> String {
    let cells: Vec<String> = cells.iter().map(|cell| cell.replace('|', "\\|")).collect();
    format!("| {} |", cells.join(" | "))
}

fn code(text: &str) -> String {
    format!("`{text}`")
}

fn code_list(items: &[&str]) -> String {
    let items: Vec<String> = items.iter().map(|item| code(item)).collect();
    items.join(", ")
}

#[cfg(test)]
mod tests {
    use super::{RULES_DOC, check, check_planned_tasks, code_list, render, row};
    use crate::tidy::registry;
    use crate::tidy::scratch::Scratch;

    /// A tree with a style guide of two reviewed rules, one lint, and an up-to-date document.
    fn tree(name: &str) -> Scratch {
        let scratch = Scratch::new(name);
        let style_guide = "# Style\n\n## Rules\n\n- One. `[review]`\n- Two. `[review]` `[fmt]`\n";
        scratch.write("docs/TIGER_STYLE.md", style_guide);
        let lint = "declare_lint! {\n/// ### What it does\n/// Sees `x`.\n\
                    pub A_LINT, Deny, \"reports a | b\" }";
        scratch.write("lints/src/lib.rs", lint);
        scratch.write(RULES_DOC, &render(scratch.root()).unwrap());
        scratch
    }

    fn rules(violations: &[crate::tidy::Violation]) -> Vec<(&'static str, u32)> {
        violations.iter().map(|violation| (violation.rule, violation.line)).collect()
    }

    // Goal: the document lists every rule with its detail, every ban and planned mechanism of
    // the registry, the declared lints with what they do, the review count and the rules that a
    // foreign gate skips.
    #[test]
    fn document_lists_the_registry() {
        let scratch = tree("rules-doc-render");
        let text = render(scratch.root()).unwrap();
        for id in registry::rule_ids() {
            assert!(text.contains(&format!("| `{id}` |")), "rule `{id}` has a row");
        }
        for planned in registry::PLANNED {
            assert!(text.contains(&format!("| `{}` |", planned.id)), "`{}`", planned.id);
        }
        assert!(text.contains("| `a_lint` | Deny | reports a \\| b | Sees `x`. |"), "lints");
        for rule in registry::RULES {
            let cells = format!("| {} | {} |", rule.summary, rule.detail);
            assert!(text.contains(&cells), "`{}` and its detail", rule.id);
        }
        assert!(text.contains("carries 2 `[review]` tags"), "review tags are counted");
        assert!(text.contains("`doc-tag`, `planned-task`, `rules-doc`."), "skipped rules");
        assert!(text.contains("registry: `doc-tag`, `doc-tool-name`."), "style guide rules");
        assert!(text.contains("| `direct-libm` | paths that start with `libm::`"), "path bans");
        assert!(text.contains("`debug_assert!`, `debug_assert_eq!`, `debug_assert_ne!`"));
        assert!(text.ends_with(".\n") && !text.ends_with("\n\n"), "one trailing newline");
    }

    // Goal: an up-to-date document passes; a stale one fails at its first differing line, and a
    // missing one fails too. Both messages name the command that fixes them.
    #[test]
    fn stale_documents_are_reported() {
        let scratch = tree("rules-doc-stale");
        assert_eq!(check(scratch.root()).unwrap(), Vec::new());
        let fresh = render(scratch.root()).unwrap();
        scratch.write(RULES_DOC, &fresh.replace("## Tidy bans", "## Tidy bans, edited by hand"));
        let stale = check(scratch.root()).unwrap();
        let line = fresh.lines().position(|line| line == "## Tidy bans").unwrap() + 1;
        assert_eq!(rules(&stale), [("rules-doc", u32::try_from(line).unwrap())]);
        assert!(stale[0].message.contains("cargo xtask rules --write"), "names the fix");
        scratch.write(RULES_DOC, &format!("{fresh}\nA line added at the end.\n"));
        assert_eq!(check(scratch.root()).unwrap().len(), 1, "an appended line is stale too");
        scratch.write("docs/TIGER_STYLE.md", "## Rules\n\n- One. `[review]`\n");
        scratch.write(RULES_DOC, &fresh);
        assert_eq!(check(scratch.root()).unwrap().len(), 1, "the review count went stale");
        std::fs::remove_file(scratch.root().join(RULES_DOC)).unwrap();
        let missing = check(scratch.root()).unwrap();
        assert_eq!(rules(&missing), [("rules-doc", 0)]);
        assert!(missing[0].message.contains("cargo xtask rules --write"), "names the fix");
    }

    // Goal: every planned mechanism needs a task with its id in an active plan; one violation
    // per id without a task, whatever the spacing of the JSON.
    #[test]
    fn planned_mechanisms_need_tasks() {
        let scratch = Scratch::new("planned-task");
        let count = registry::PLANNED.len();
        assert_eq!(check_planned_tasks(scratch.root()).unwrap().len(), count, "no plans at all");
        let mut ids = registry::PLANNED.iter().map(|planned| planned.id);
        let first = ids.next().expect("something is planned");
        let tasks: Vec<String> = ids.map(|id| format!("{{ \"id\" :\n\"{id}\" }}")).collect();
        scratch.write("docs/exec-plans/active/a/tasks.json", &tasks.join(",\n"));
        let missing = check_planned_tasks(scratch.root()).unwrap();
        assert_eq!(rules(&missing), [("planned-task", 0)]);
        assert!(missing[0].message.contains(&format!("`{first}`")), "names the missing id");
        scratch.write("docs/exec-plans/active/b/notes.json", &format!("\"id\": \"{first}\""));
        assert_eq!(check_planned_tasks(scratch.root()).unwrap().len(), 1, "only tasks.json");
        scratch.write("docs/exec-plans/completed/c/tasks.json", &format!("\"id\": \"{first}\""));
        assert_eq!(check_planned_tasks(scratch.root()).unwrap().len(), 1, "only active plans");
        scratch.write("docs/exec-plans/active/b/tasks.json", &format!("\"id\": \"{first}\""));
        assert_eq!(check_planned_tasks(scratch.root()).unwrap(), Vec::new());
    }

    // Goal: the repository's own document is what the registry generates.
    #[test]
    fn committed_document_is_current() {
        let root = crate::workspace_root();
        let committed = std::fs::read_to_string(root.join(RULES_DOC)).unwrap();
        assert_eq!(committed, render(&root).unwrap(), "run `cargo xtask rules --write`");
    }

    // Goal: table cells escape the column separator, and lists are comma-separated code.
    #[test]
    fn rows_and_lists_are_formatted() {
        assert_eq!(row(&["a", "b|c"]), "| a | b\\|c |");
        assert_eq!(code_list(&["a", "b"]), "`a`, `b`");
        assert_eq!(code_list(&[]), "");
    }
}
